'use strict';
const {app,BrowserWindow,dialog}=require('electron');
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path'),Module=require('node:module');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'v6-result-io-main-'));
app.setPath('userData',path.join(root,'profile'));
const storage=require('../engine/storage'),isolated=new Module(path.join(root,'engine/storage.js'));
isolated.filename=path.join(root,'engine/storage.js');isolated._compile(fs.readFileSync(path.join(__dirname,'../engine/storage.js'),'utf8'),isolated.filename);Object.assign(storage,isolated.exports);
app.on('browser-window-created',(_e,w)=>w.once('ready-to-show',()=>w.hide()));
require('../main');
app.whenReady().then(async()=>{try{
  const w=BrowserWindow.getAllWindows()[0];if(w.webContents.isLoading())await new Promise(r=>w.webContents.once('did-finish-load',r));
  const invoke=(cmd,payload={})=>w.webContents.executeJavaScript('v6api.invoke('+JSON.stringify(cmd)+','+JSON.stringify(payload)+')');
  const rows=Array.from({length:40000},(_,i)=>Array.from({length:20},(_,j)=>i+':'+j+' 中文,"值"'));
  const fields=Array.from({length:20},(_,i)=>({name:'字段'+i}));
  const folder=path.join(storage.tasksDir(),'runs');fs.mkdirSync(folder,{recursive:true});
  fs.writeFileSync(path.join(folder,'123.json'),JSON.stringify({summary:{name:'后台历史',total:40000},fields,rows,logs:[{time:'fixture',message:'历史日志'}]}));
  let beats=0,maxGap=0,last=performance.now();
  const tick=setInterval(()=>{const now=performance.now();maxGap=Math.max(maxGap,now-last);last=now;beats++;},5);
  const first=await invoke('run-results',{id:'123',page:399});
  assert.equal(first.ok,true);assert.equal(first.total,40000);assert.equal(first.rows.length,100);assert.equal(first.rows[0][0],'39900:0 中文,"值"');
  const exported=await invoke('export-run',{id:'123',format:'xlsx'});assert.equal(exported.ok,true,exported.error);assert.equal(exported.count,40000);
  const history=await invoke('run-history');assert.equal(history.history[0].name,'后台历史');
  const logged=await invoke('export-logs',{id:'123'});assert.equal(fs.readFileSync(logged.path,'utf8'),'[fixture] 历史日志');
  clearInterval(tick);assert.ok(beats>10);assert.ok(maxGap<250,'历史和导出不应冻结主进程，实际 '+maxGap.toFixed(1)+'ms');
  const invalid=await invoke('run-results',{id:'../123'});assert.equal(invalid.ok,false);
  const resultIO=require('../engine/result-io'),readJournal=resultIO.readJournalAsync;
  let releaseRestore;
  resultIO.readJournalAsync=()=>new Promise(resolve=>{releaseRestore=resolve;});
  dialog.showOpenDialog=async()=>({canceled:false,filePaths:['controlled-backup.jsonl']});
  const restoring=invoke('recover-result-backup');
  while(!releaseRestore)await new Promise(r=>setTimeout(r,5));
  assert.equal((await invoke('task-new')).ok,true);
  releaseRestore({fields:[{name:'旧备份'}],rows:[['不能覆盖新任务']]});
  const stale=await restoring;assert.equal(stale.ok,false,'任务切换后不能应用旧备份回复');
  assert.equal((await invoke('get-state')).total,0);resultIO.readJournalAsync=readJournal;
  console.log(JSON.stringify({pass:true,rows:40000,columns:20,maxMainGapMs:Math.round(maxGap),heartbeats:beats,historyPageRows:first.rows.length}));
  app.exit(0);
}catch(error){console.error(error);app.exit(1);}});
